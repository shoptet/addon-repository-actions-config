/**
 * Rule-set equality test (A3).
 *
 * Asserts that this repository's EFFECTIVE rule set — what `review.js` (via
 * `profiles.js`) actually reports — equals the shared packages' DECLARED set,
 * by rule id and severity ONLY. Never message text, never report ranges
 * (`endColumn` etc.): across ESLint 9.39.5 and 10.8.0 exactly two rules
 * diverge there (`max-depth`'s `endColumn`, `no-useless-assignment`'s
 * message), and this repo runs 9 while the CLI runs 10 — asserting on either
 * would fail for reasons that have nothing to do with policy.
 *
 * `RELIABLE_RULES` is read from each package's own named export
 * (`require('@shoptet/addon-*').RELIABLE_RULES`), never a local copy — a
 * test comparing a copy to itself always passes trivially. See the review
 * checklist in doc/plans/rule-unification/a3.md.
 *
 * Two independent sources feed the comparison:
 *
 *  - DECLARED severity: read directly off each package's own config module
 *    (`eslint.flat.config.js`'s `rules` object, `stylelint.config.js`'s
 *    `rules` object). This is what the package's author configured.
 *
 *  - EFFECTIVE severity: read off `test-cases/expected.json`, which is a
 *    machine-checked snapshot of what `review.js` ACTUALLY reports when run
 *    against a fixture that triggers the rule (see test/selftest.js and
 *    a0-baseline.md's own methodology — "measured by running the code path,
 *    not by reading a static file"). expected.json is regenerated by hand
 *    whenever a fixture's behavior changes, so it tracks runtime behaviour,
 *    not the config source.
 *
 * A rule that diverges between these two sources is exactly the kind of
 * drift A2's extraction was supposed to make impossible: someone edits
 * `eslint.flat.config.js`'s severity for a rule but the fixture snapshot
 * (and therefore what a partner actually sees) never caught up, or vice
 * versa.
 *
 * The HTML package (`@shoptet/addon-html-lint`) has no declarative `rules`
 * object to read severity off — its three checks hardcode severity in code
 * (`lib/html-checks.js`). So its DECLARED side is measured the same way A0
 * measured it: by actually invoking the package's own pure
 * `lintHtmlSource(html, filePath)` against a minimal snippet that triggers
 * each rule, and reading the severity off the returned finding. That keeps
 * "declared" sourced from the package, never from a value written into this
 * test file.
 *
 * Runner-synthesized rule ids — `CodeQuality` (fatal parse-error catch-all),
 * `shoptet/es-module-required` (emitted by `linters/eslint-linter.js`, not by
 * a rule object), `CssSyntaxError` / `stylelint/parse-error` (parse-failure
 * catch-alls emitted by `linters/stylelint-linter.js`) — are not entries in
 * any package's `rules` object by construction, so they are exempted from
 * the "declared severity" side the same way test/selftest.js already exempts
 * `stylelint/parse-error` from fixture-coverage. Their severity is instead
 * cross-checked directly against the runner source that emits them, listed
 * in RUNNER_SYNTHESIZED below.
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const CASES = path.join(ROOT, 'test-cases');

let failures = 0;
function pass(msg) {
  console.log(`  ✓ ${msg}`);
}
function fail(msg) {
  failures += 1;
  console.error(`  ✗ ${msg}`);
}

// ── Load the packages' own named exports — never a local copy ──
const eslintPkg = require('@shoptet/addon-eslint-config');
const stylelintPkg = require('@shoptet/addon-stylelint-config');
const htmlPkg = require('@shoptet/addon-html-lint');

/** Normalize an ESLint/stylelint severity token to this repo's two-level scale. */
function normalizeEslintSeverity(token) {
  if (token === 'off' || token === 0) return null;
  if (token === 'warn' || token === 1) return 'recommend';
  if (token === 'error' || token === 2) return 'blocker';
  throw new Error(`Unrecognized ESLint severity token: ${JSON.stringify(token)}`);
}

/** Flatten a flat-config array's `rules` objects into { ruleId: 'blocker'|'recommend' }. */
function flattenEslintConfig(flatConfigArray) {
  const declared = {};
  for (const entry of flatConfigArray) {
    if (!entry || typeof entry !== 'object' || !entry.rules) continue;
    for (const [ruleId, value] of Object.entries(entry.rules)) {
      const token = Array.isArray(value) ? value[0] : value;
      const severity = normalizeEslintSeverity(token);
      if (severity === null) {
        delete declared[ruleId]; // explicit 'off' — not configured
      } else {
        declared[ruleId] = severity;
      }
    }
  }
  return declared;
}

/** Flatten a stylelint config's `rules` object into { ruleId: 'blocker'|'recommend' }. */
function flattenStylelintConfig(stylelintConfig) {
  const declared = {};
  for (const [ruleId, value] of Object.entries(stylelintConfig.rules)) {
    if (value === false || value === null) continue; // off — not configured
    let severity = 'blocker'; // stylelint default when no explicit severity option
    if (Array.isArray(value) && value[1] && typeof value[1] === 'object' && value[1].severity) {
      severity = value[1].severity === 'warning' ? 'recommend' : 'blocker';
    }
    declared[ruleId] = severity;
  }
  return declared;
}

/**
 * HTML has no declarative rules object — measure declared severity by
 * running the package's own pure function against a snippet built to
 * trigger each RELIABLE_RULES id, exactly once each.
 */
function measureHtmlDeclaredSeverities() {
  const triggers = {
    'a11y/img-alt': '<img src="x.png">',
    'html/no-inline-script': '<script>var x = 1;</script>',
    'html/deprecated-tag': '<center>hi</center>',
  };
  const declared = {};
  for (const [ruleId, snippet] of Object.entries(triggers)) {
    const findings = htmlPkg.lintHtmlSource(snippet, 'probe.html');
    const hit = findings.find((f) => f.ruleId === ruleId);
    if (!hit) {
      throw new Error(`HTML probe for ${ruleId} produced no finding — trigger snippet is stale`);
    }
    declared[ruleId] = hit.severity === 'blocker' ? 'blocker' : 'recommend';
  }
  return declared;
}

// Deliberately-configured-but-excluded: rules a package's config turns on
// for one linter, but which are absent from THAT PACKAGE's own
// RELIABLE_RULES slice by design, documented in a0-baseline.md ("Note: the
// stylelint config also sets shoptet/no-testid-selector: true, but that rule
// id is not in the stylelint package's RELIABLE_RULES slice, so a positive
// from it is filtered out of the gate's output entirely"). Keyed by
// `${package}:${ruleId}` so this can never accidentally exempt the
// SAME-NAMED rule in a DIFFERENT package's own RELIABLE_RULES slice — the
// ESLint-side `shoptet/no-testid-selector` is a distinct rule of the same
// name and IS reliable there.
const DELIBERATE_EXCLUSIONS = new Set(['stylelint:shoptet/no-testid-selector']);

// Rule ids the runner synthesizes itself rather than any package's config —
// cross-checked against the source that actually emits them (comment on each
// line names the file/behaviour), not against a config object that doesn't
// exist for them.
const RUNNER_SYNTHESIZED = {
  // linters/eslint-linter.js: fatal parse error, no ruleId from ESLint itself
  CodeQuality: 'blocker',
  // linters/eslint-linter.js: file parses as script but not as ES module
  'shoptet/es-module-required': 'blocker',
  // linters/stylelint-linter.js: CSS that fails to parse
  CssSyntaxError: 'blocker',
  // linters/stylelint-linter.js: defensive postcss channel (COVERAGE_EXEMPT
  // in selftest.js too — ordinary syntax errors surface as CssSyntaxError)
  'stylelint/parse-error': 'blocker',
};

/** Load and parse `severity` out of a `rule@severity[:count]` tag. */
function loadEffectiveSeverities() {
  const spec = JSON.parse(fs.readFileSync(path.join(CASES, 'expected.json'), 'utf8'));
  delete spec.$comment;
  const effective = {};
  for (const rules of Object.values(spec)) {
    for (const tag of rules) {
      const m = tag.match(/^(.*)@(blocker|recommend)(?::\d+)?$/);
      if (!m) throw new Error(`expected.json: unparseable tag ${JSON.stringify(tag)}`);
      const [, ruleId, severity] = m;
      if (effective[ruleId] && effective[ruleId] !== severity) {
        throw new Error(
          `expected.json: ${ruleId} is pinned at both ${effective[ruleId]} and ${severity} across fixtures`,
        );
      }
      effective[ruleId] = severity;
    }
  }
  return effective;
}

function main() {
  console.log('rule-set equality (A3):');

  const declaredEslint = flattenEslintConfig(eslintPkg.configs.recommended);
  const declaredStylelint = flattenStylelintConfig(stylelintPkg.configs.recommended);
  const declaredHtml = measureHtmlDeclaredSeverities();
  const effective = loadEffectiveSeverities();

  const packages = [
    { name: 'eslint', reliable: eslintPkg.RELIABLE_RULES, declared: declaredEslint },
    { name: 'stylelint', reliable: stylelintPkg.RELIABLE_RULES, declared: declaredStylelint },
    { name: 'html', reliable: htmlPkg.RELIABLE_RULES, declared: declaredHtml },
  ];

  // ── Case 3: a rule CONFIGURED (declared, non-off) but ABSENT from
  // RELIABLE_RULES — configured yet never reportable. Not itself a bug (see
  // profiles.js's own comment — absence is a trust decision), but it must be
  // a DELIBERATE one: flag it so a silent drop is visible, not undetectable.
  for (const { name, reliable, declared } of packages) {
    for (const ruleId of Object.keys(declared)) {
      if (RUNNER_SYNTHESIZED[ruleId]) continue;
      if (reliable.has(ruleId)) continue;
      if (DELIBERATE_EXCLUSIONS.has(`${name}:${ruleId}`)) continue;
      fail(
        `[${name}] ${ruleId}: configured (${declared[ruleId]}) but absent from RELIABLE_RULES — ` +
          `configured yet never reportable`,
      );
    }
  }
  if (failures === 0) pass('every configured rule is in its package’s RELIABLE_RULES');

  // ── Case 4: a rule in RELIABLE_RULES that NOTHING configures — an orphan
  // allowlist entry, usually a typo or a rule removed from config without
  // being removed from the allowlist too.
  const beforeCase4 = failures;
  for (const { name, reliable, declared } of packages) {
    for (const ruleId of reliable) {
      if (RUNNER_SYNTHESIZED[ruleId]) continue;
      if (ruleId in declared) continue;
      fail(`[${name}] ${ruleId}: in RELIABLE_RULES but nothing configures it`);
    }
  }
  if (failures === beforeCase4) pass('every RELIABLE_RULES entry is configured by its package');

  // ── Case 1 + Case 2: for every rule this repo can actually measure
  // (pinned by a fixture in expected.json, i.e. proven reachable through
  // review.js), the package's own declared severity must equal what
  // review.js effectively reports. A mismatch here is either:
  //   - case 1, in spirit: the rule fires but at the wrong severity, which
  //     is observationally identical to "missing from the effective set" at
  //     the level that matters (whether it blocks the PR) whenever declared
  //     says blocker and effective says recommend or absent;
  //   - case 2: severity differs outright.
  const beforeCase12 = failures;
  const allDeclared = {
    ...declaredEslint,
    ...declaredStylelint,
    ...declaredHtml,
    ...RUNNER_SYNTHESIZED,
  };
  for (const [ruleId, effectiveSeverity] of Object.entries(effective)) {
    if (!(ruleId in allDeclared)) {
      // Pinned by a fixture but not declared anywhere — only possible for a
      // rule id that belongs to none of the three packages, which the
      // completeness check below also catches from the other direction.
      continue;
    }
    const declaredSeverity = allDeclared[ruleId];
    if (declaredSeverity !== effectiveSeverity) {
      fail(
        `${ruleId}: declared ${declaredSeverity} in its package's config but ` +
          `review.js effectively reports it as ${effectiveSeverity} (test-cases/expected.json)`,
      );
    }
  }
  if (failures === beforeCase12) {
    pass('every fixture-measured rule’s effective severity matches its declared severity');
  }

  // ── Completeness in the other direction: every RELIABLE_RULES rule (across
  // all three packages, i.e. what profiles.js reports) must be measurable —
  // present in expected.json — so this equality test can never be silently
  // blind to a rule nobody's fixture pins. (test/selftest.js's own section 5
  // enforces the same thing for fixture-coverage reasons; restated here so
  // this file is independently meaningful.)
  const beforeCoverage = failures;
  const COVERAGE_EXEMPT = new Set(['stylelint/parse-error']);
  const mergedReliable = new Set([
    ...eslintPkg.RELIABLE_RULES,
    ...stylelintPkg.RELIABLE_RULES,
    ...htmlPkg.RELIABLE_RULES,
  ]);
  for (const ruleId of mergedReliable) {
    if (COVERAGE_EXEMPT.has(ruleId)) continue;
    if (!(ruleId in effective)) {
      fail(`${ruleId}: in the merged RELIABLE_RULES set but not measurable via expected.json`);
    }
  }
  if (failures === beforeCoverage) pass('every RELIABLE_RULES entry is measurable');

  if (failures > 0) {
    console.error(`\n${failures} rule-equality failure(s).`);
    process.exitCode = 1;
  } else {
    console.log('\nRule set equality holds: declared == effective, by id and severity.');
  }
}

main();
