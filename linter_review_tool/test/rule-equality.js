/**
 * Rule-set equality test (A3).
 *
 * Asserts that this repository's EFFECTIVE rule set — what `review.js` (via
 * `profiles.js`) actually reports — equals the shared packages' DECLARED set,
 * by rule id and severity ONLY. Never message text, never report ranges
 * (`endColumn` etc.): across ESLint 9.39.5 and 10.8.0 exactly two rules
 * diverge there (`max-depth`'s `endColumn`, `no-useless-assignment`'s
 * message), and this repo runs 9 while the CLI runs 10 — asserting on either
 * would fail for reasons that have nothing to do with policy.
 *
 * `RELIABLE_RULES` is read from each package's own named export
 * (`require('@shoptet/addon-*').RELIABLE_RULES`), never a local copy — a
 * test comparing a copy to itself always passes trivially. See the review
 * checklist in doc/plans/rule-unification/a3.md.
 *
 * Two independent sources feed the comparison:
 *
 *  - DECLARED severity: read directly off each package's own config module
 *    (`eslint.flat.config.js`'s `rules` object, `stylelint.config.js`'s
 *    `rules` object). This is what the package's author configured.
 *
 *  - EFFECTIVE severity: read off `test-cases/expected.json`, which is a
 *    machine-checked snapshot of what `review.js` ACTUALLY reports when run
 *    against a fixture that triggers the rule (see test/selftest.js and
 *    a0-baseline.md's own methodology — "measured by running the code path,
 *    not by reading a static file"). expected.json is regenerated by hand
 *    whenever a fixture's behavior changes, so it tracks runtime behaviour,
 *    not the config source.
 *
 * A rule that diverges between these two sources is exactly the kind of
 * drift A2's extraction was supposed to make impossible: someone edits
 * `eslint.flat.config.js`'s severity for a rule but the fixture snapshot
 * (and therefore what a partner actually sees) never caught up, or vice
 * versa.
 *
 * The HTML package (`@shoptet/addon-html-lint`) has no declarative `rules`
 * object to read severity off — its three checks hardcode severity in code
 * (`lib/html-checks.js`). So its DECLARED side is measured the same way A0
 * measured it: by actually invoking the package's own pure
 * `lintHtmlSource(html, filePath)` against a minimal snippet that triggers
 * each rule, and reading the severity off the returned finding. That keeps
 * "declared" sourced from the package, never from a value written into this
 * test file.
 *
 * Runner-synthesized rule ids — `CodeQuality` (fatal parse-error catch-all),
 * `shoptet/es-module-required` (emitted by `linters/eslint-linter.js`, not by
 * a rule object), `CssSyntaxError` / `stylelint/parse-error` (parse-failure
 * catch-alls emitted by `linters/stylelint-linter.js`) — are not entries in
 * any package's `rules` object by construction, so they are exempted from
 * the "declared severity" side the same way test/selftest.js already exempts
 * `stylelint/parse-error` from fixture-coverage.
 *
 * WHICH ids those are is read from each package's own `RUNNER_RULES` named
 * export, not from a list in this file. Their SEVERITY is not: a
 * runner-synthesized finding's severity is a property of this repository's
 * runner (`linters/*.js`), which is the thing that constructs the finding —
 * the package can only declare that it expects the id to come from
 * elsewhere. So severity stays in the local RUNNER_SEVERITY map below,
 * cross-checked against the runner source, and its key set is asserted equal
 * to the union of the packages' `RUNNER_RULES` so the two can never drift
 * apart silently.
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const CASES = path.join(ROOT, 'test-cases');

let failures = 0;
function pass(msg) {
  console.log(`  ✓ ${msg}`);
}
function fail(msg) {
  failures += 1;
  console.error(`  ✗ ${msg}`);
}

// ── Load the packages' own named exports — never a local copy ──
const eslintPkg = require('@shoptet/addon-eslint-config');
const stylelintPkg = require('@shoptet/addon-stylelint-config');
const htmlPkg = require('@shoptet/addon-html-lint');

/** Normalize an ESLint/stylelint severity token to this repo's two-level scale. */
function normalizeEslintSeverity(token) {
  if (token === 'off' || token === 0) return null;
  if (token === 'warn' || token === 1) return 'recommend';
  if (token === 'error' || token === 2) return 'blocker';
  throw new Error(`Unrecognized ESLint severity token: ${JSON.stringify(token)}`);
}

// One probe file per extension review.js hands to ESLint. Never created on
// disk — calculateConfigForFile resolves the config from the path alone.
const JS_PROBE_EXTENSIONS = ['js', 'mjs', 'cjs'];
const TS_PROBE_EXTENSIONS = ['jsx', 'ts', 'tsx', 'mts', 'cts'];
const ESLINT_PROBE_EXTENSIONS = [...JS_PROBE_EXTENSIONS, ...TS_PROBE_EXTENSIONS];

// The documented difference between the JavaScript and the TypeScript/JSX
// rule set (README, "TypeScript is checked by syntax only"): each core rule
// on the left runs under the id on the right on TS/JSX, at the same severity;
// `null` = deliberately not run on TS/JSX. Any other difference is drift.
const TYPESCRIPT_SWAPS = {
  'no-unused-vars': '@typescript-eslint/no-unused-vars',
  'no-use-before-define': '@typescript-eslint/no-use-before-define',
  'no-unused-expressions': '@typescript-eslint/no-unused-expressions',
  camelcase: 'shoptet/camelcase',
  'no-var': 'shoptet/no-var',
  'no-redeclare': null,
  'getter-return': null,
};
// `.jsx` is plain JavaScript on the TypeScript parser: no tsc runs and no
// `declare` exists, so these swaps do not apply to it — it keeps the core rule.
const JSX_KEEPS_CORE = new Set(['no-redeclare', 'no-var', 'getter-return']);

/**
 * Measure the ESLint package's DECLARED severities: the rules ESLint actually
 * applies to each linted extension, computed by ESLint itself from the
 * package's flat config (`calculateConfigForFile`), so a block's `files`
 * scoping and an `'off'` are resolved exactly as at lint time. A rule is
 * declared when it is on for at least one extension — the TypeScript block
 * swaps `no-unused-vars` for `@typescript-eslint/no-unused-vars`, so neither
 * is on everywhere. Turning a rule off for an extension it used to run on
 * (`{ files: ['**\/*.js'], rules: { 'no-console': 'off' } }`) fails in
 * assertSameRulesPerExtension below, whether or not a fixture of that
 * extension exists. A rule on at two different severities on two extensions
 * would make the gate depend on the file extension — that is drift, and it
 * fails here too.
 */
async function measureEslintDeclaredSeverities(flatConfigArray) {
  const { ESLint } = require('eslint');
  const eslint = new ESLint({
    cwd: ROOT,
    overrideConfigFile: true,
    overrideConfig: flatConfigArray,
  });
  const declared = {};
  const firstSeenOn = {}; // ruleId → the extension that set declared[ruleId]
  const perExtension = {}; // ext → { ruleId: severity } (rules that are on)
  for (const ext of ESLINT_PROBE_EXTENSIONS) {
    const config = await eslint.calculateConfigForFile(path.join(ROOT, `probe.${ext}`));
    if (!config) throw new Error(`eslint config: no configuration matches .${ext}`);
    perExtension[ext] = {};
    for (const [ruleId, value] of Object.entries(config.rules)) {
      const severity = normalizeEslintSeverity(Array.isArray(value) ? value[0] : value);
      if (severity === null) continue;
      perExtension[ext][ruleId] = severity;
      if (declared[ruleId] && declared[ruleId] !== severity) {
        fail(
          `[eslint] ${ruleId}: ${declared[ruleId]} on .${firstSeenOn[ruleId]} but ${severity} on .${ext} — gate behaviour depends on the extension`,
        );
        continue;
      }
      if (!declared[ruleId]) firstSeenOn[ruleId] = ext;
      declared[ruleId] = severity;
    }
  }
  assertSameRulesPerExtension(perExtension);
  return declared;
}

/** `a` and `b` ({ ruleId: severity }) as a list of human-readable differences. */
function ruleSetDiff(a, b) {
  const diffs = [];
  for (const id of new Set([...Object.keys(a), ...Object.keys(b)])) {
    if (a[id] !== b[id]) diffs.push(`${id}: ${a[id] || 'off'} vs ${b[id] || 'off'}`);
  }
  return diffs;
}

/**
 * Every JS extension must run the same rules as `.js`, every TS extension the
 * `.js` rules with exactly TYPESCRIPT_SWAPS applied, and `.jsx` the same but
 * keeping JSX_KEEPS_CORE — so an
 * `'off'` (or a severity change) scoped to some extensions fails here, not
 * only where a fixture of that extension happens to exist.
 */
function assertSameRulesPerExtension(perExtension) {
  const before = failures;
  const jsRules = perExtension.js;
  const swapped = (keepCore) => {
    const rules = {};
    for (const [id, severity] of Object.entries(jsRules)) {
      if (!(id in TYPESCRIPT_SWAPS) || keepCore.has(id)) rules[id] = severity;
      else if (TYPESCRIPT_SWAPS[id]) rules[TYPESCRIPT_SWAPS[id]] = severity;
    }
    return rules;
  };
  const expectedTs = swapped(new Set());
  const expectedJsx = swapped(JSX_KEEPS_CORE);
  for (const ext of ESLINT_PROBE_EXTENSIONS) {
    let expected = expectedTs;
    if (JS_PROBE_EXTENSIONS.includes(ext)) expected = jsRules;
    else if (ext === 'jsx') expected = expectedJsx;
    for (const diff of ruleSetDiff(expected, perExtension[ext])) {
      fail(`[eslint] .${ext} differs from the documented rule set — ${diff}`);
    }
  }
  if (failures === before) {
    pass(
      'every JS extension runs the .js rules; every TS/JSX extension those rules with the documented swaps',
    );
  }

  // The runner drops a replaced core rule's reports on TS/JSX (an inline
  // config comment can switch it back on). Its sets must be exactly the core
  // rules the config turns off there — no more (that would hide a real rule),
  // no less (a re-enabled core rule would misread TypeScript).
  const { CORE_RULES_REPLACED_ON } = require('../linters/eslint-linter');
  const beforeReplaced = failures;
  for (const ext of TS_PROBE_EXTENSIONS) {
    const offHere = Object.keys(jsRules)
      .filter((id) => !(id in perExtension[ext]))
      .sort();
    const runnerSet = [...CORE_RULES_REPLACED_ON[ext === 'jsx' ? 'jsx' : 'ts']].sort();
    if (offHere.join(',') !== runnerSet.join(',')) {
      fail(
        `[eslint] .${ext}: config turns off [${offHere.join(', ')}] but the runner drops [${runnerSet.join(', ')}]`,
      );
    }
  }
  if (failures === beforeReplaced) {
    pass('the runner drops exactly the core rules the config replaces on each TS/JSX extension');
  }

  // Core rules replaced on EVERY extension: off everywhere, and their
  // shoptet/* variant on everywhere — otherwise the runner would drop a rule
  // that is still the one reporting.
  const { CORE_RULES_REPLACED_EVERYWHERE } = require('../linters/eslint-linter');
  const beforeEverywhere = failures;
  for (const id of CORE_RULES_REPLACED_EVERYWHERE) {
    for (const ext of ESLINT_PROBE_EXTENSIONS) {
      if (id in perExtension[ext]) fail(`[eslint] .${ext}: ${id} is on, but the runner drops it`);
      if (!(`shoptet/${id}` in perExtension[ext])) {
        fail(`[eslint] .${ext}: shoptet/${id} (the replacement of ${id}) is not on`);
      }
    }
  }
  if (failures === beforeEverywhere) {
    pass(
      `core rules replaced everywhere (${[...CORE_RULES_REPLACED_EVERYWHERE].join(', ')}) are off on every extension and their shoptet/* variant is on`,
    );
  }
}

/**
 * The ESLint engine (this tool's `eslint`) and the core rules the package
 * reaches through `eslint/use-at-your-own-risk` (shoptet/camelcase, the
 * typescript-eslint extension rules — resolved from the package's location,
 * i.e. the workspace root) come from two installs locked in two lockfiles.
 * They must be the same version, or upgrading one would run another
 * version's core rules inside this engine.
 */
function assertSingleEslintVersion() {
  const engine = require('eslint/package.json').version;
  const packageDir = path.dirname(require.resolve('@shoptet/addon-eslint-config/package.json'));
  const rules = require(require.resolve('eslint/package.json', { paths: [packageDir] })).version;
  if (engine === rules) pass(`one ESLint version for engine and rule package (${engine})`);
  else fail(`ESLint ${engine} runs the lint, but the rule package resolves ESLint ${rules}`);
}

/** Flatten a stylelint config's `rules` object into { ruleId: 'blocker'|'recommend' }. */
function flattenStylelintConfig(stylelintConfig) {
  const declared = {};
  for (const [ruleId, value] of Object.entries(stylelintConfig.rules)) {
    if (value === false || value === null) continue; // off — not configured
    let severity = 'blocker'; // stylelint default when no explicit severity option
    if (Array.isArray(value) && value[1] && typeof value[1] === 'object' && value[1].severity) {
      severity = value[1].severity === 'warning' ? 'recommend' : 'blocker';
    }
    declared[ruleId] = severity;
  }
  return declared;
}

/**
 * HTML has no declarative rules object — measure declared severity by
 * running the package's own pure function against a snippet built to
 * trigger each RELIABLE_RULES id, exactly once each.
 */
function measureHtmlDeclaredSeverities() {
  const triggers = {
    'a11y/img-alt': '<img src="x.png">',
    'html/no-inline-script': '<script>var x = 1;</script>',
    'html/deprecated-tag': '<center>hi</center>',
  };
  const declared = {};
  for (const [ruleId, snippet] of Object.entries(triggers)) {
    const findings = htmlPkg.lintHtmlSource(snippet, 'probe.html');
    const hit = findings.find((f) => f.ruleId === ruleId);
    if (!hit) {
      throw new Error(`HTML probe for ${ruleId} produced no finding — trigger snippet is stale`);
    }
    declared[ruleId] = hit.severity === 'blocker' ? 'blocker' : 'recommend';
  }
  return declared;
}

// Deliberately-configured-but-excluded: rules a package's config turns on
// for one linter, but which are absent from THAT PACKAGE's own
// RELIABLE_RULES slice by design, documented in a0-baseline.md ("Note: the
// stylelint config also sets shoptet/no-testid-selector: true, but that rule
// id is not in the stylelint package's RELIABLE_RULES slice, so a positive
// from it is filtered out of the gate's output entirely"). Keyed by
// `${package}:${ruleId}` so this can never accidentally exempt the
// SAME-NAMED rule in a DIFFERENT package's own RELIABLE_RULES slice — the
// ESLint-side `shoptet/no-testid-selector` is a distinct rule of the same
// name and IS reliable there.
const DELIBERATE_EXCLUSIONS = new Set(['stylelint:shoptet/no-testid-selector']);

// Severity of each runner-synthesized rule id, cross-checked against the
// runner source that actually emits it (the comment on each line names the
// file/behaviour) — there is no config object to read it off. The id set
// itself comes from the packages' `RUNNER_RULES` exports; `assertRunnerRules`
// below asserts the two agree.
const RUNNER_SEVERITY = {
  // linters/eslint-linter.js: fatal parse error, no ruleId from ESLint itself
  CodeQuality: 'blocker',
  // linters/eslint-linter.js: file parses as script but not as ES module
  'shoptet/es-module-required': 'blocker',
  // linters/stylelint-linter.js: CSS that fails to parse
  CssSyntaxError: 'blocker',
  // linters/stylelint-linter.js: defensive postcss channel (COVERAGE_EXEMPT
  // in selftest.js too — ordinary syntax errors surface as CssSyntaxError)
  'stylelint/parse-error': 'blocker',
};

/** Load and parse `severity` out of a `rule@severity[:count]` tag. */
function loadEffectiveSeverities() {
  const spec = JSON.parse(fs.readFileSync(path.join(CASES, 'expected.json'), 'utf8'));
  delete spec.$comment;
  const effective = {};
  for (const rules of Object.values(spec)) {
    for (const tag of rules) {
      const m = tag.match(/^(.*)@(blocker|recommend)(?::\d+)?$/);
      if (!m) throw new Error(`expected.json: unparseable tag ${JSON.stringify(tag)}`);
      const [, ruleId, severity] = m;
      if (effective[ruleId] && effective[ruleId] !== severity) {
        throw new Error(
          `expected.json: ${ruleId} is pinned at both ${effective[ruleId]} and ${severity} across fixtures`,
        );
      }
      effective[ruleId] = severity;
    }
  }
  return effective;
}

async function main() {
  console.log('rule-set equality (A3):');

  assertSingleEslintVersion();
  const declaredEslint = await measureEslintDeclaredSeverities(eslintPkg.configs.recommended);
  const declaredStylelint = flattenStylelintConfig(stylelintPkg.configs.recommended);
  const declaredHtml = measureHtmlDeclaredSeverities();
  const effective = loadEffectiveSeverities();

  const packages = [
    {
      name: 'eslint',
      reliable: eslintPkg.RELIABLE_RULES,
      declared: declaredEslint,
      runner: eslintPkg.RUNNER_RULES,
    },
    {
      name: 'stylelint',
      reliable: stylelintPkg.RELIABLE_RULES,
      declared: declaredStylelint,
      runner: stylelintPkg.RUNNER_RULES,
    },
    // The HTML package's checks are all emitted by the package itself, so it
    // declares no RUNNER_RULES export at all — an empty set, not a missing one.
    { name: 'html', reliable: htmlPkg.RELIABLE_RULES, declared: declaredHtml, runner: new Set() },
  ];

  // ── Case 0: the packages' own `RUNNER_RULES` exports must be (a) a subset
  // of that package's `RELIABLE_RULES` — a runner id nothing allowlists can
  // never reach output — and (b) collectively exactly the id set this test
  // knows a runner severity for. (b) is what keeps consuming the export from
  // weakening the test: the packages own the membership, this repo's runner
  // owns the severity, and a package adding or dropping a runner id without
  // the runner following fails here rather than silently skipping a rule.
  const beforeCase0 = failures;
  const runnerIdsFromPackages = new Set();
  for (const { name, reliable, runner } of packages) {
    for (const ruleId of runner) {
      runnerIdsFromPackages.add(ruleId);
      if (!reliable.has(ruleId)) {
        fail(`[${name}] ${ruleId}: in RUNNER_RULES but not in that package's RELIABLE_RULES`);
      }
    }
  }
  for (const ruleId of runnerIdsFromPackages) {
    if (!(ruleId in RUNNER_SEVERITY)) {
      fail(
        `${ruleId}: exported in a package's RUNNER_RULES but this test knows no runner severity`,
      );
    }
  }
  for (const ruleId of Object.keys(RUNNER_SEVERITY)) {
    if (!runnerIdsFromPackages.has(ruleId)) {
      fail(`${ruleId}: has a runner severity here but no package exports it in RUNNER_RULES`);
    }
  }
  if (failures === beforeCase0) {
    pass('RUNNER_RULES ⊆ RELIABLE_RULES in every package, and matches the runner severity map');
  }

  // ── Case 3: a rule CONFIGURED (declared, non-off) but ABSENT from
  // RELIABLE_RULES — configured yet never reportable. Not itself a bug (see
  // profiles.js's own comment — absence is a trust decision), but it must be
  // a DELIBERATE one: flag it so a silent drop is visible, not undetectable.
  const beforeCase3 = failures;
  for (const { name, reliable, declared, runner } of packages) {
    for (const ruleId of Object.keys(declared)) {
      if (runner.has(ruleId)) continue;
      if (reliable.has(ruleId)) continue;
      if (DELIBERATE_EXCLUSIONS.has(`${name}:${ruleId}`)) continue;
      fail(
        `[${name}] ${ruleId}: configured (${declared[ruleId]}) but absent from RELIABLE_RULES — ` +
          `configured yet never reportable`,
      );
    }
  }
  if (failures === beforeCase3) pass('every configured rule is in its package’s RELIABLE_RULES');

  // ── Case 4: a rule in RELIABLE_RULES that NOTHING configures — an orphan
  // allowlist entry, usually a typo or a rule removed from config without
  // being removed from the allowlist too.
  const beforeCase4 = failures;
  for (const { name, reliable, declared, runner } of packages) {
    for (const ruleId of reliable) {
      if (runner.has(ruleId)) continue;
      if (ruleId in declared) continue;
      fail(`[${name}] ${ruleId}: in RELIABLE_RULES but nothing configures it`);
    }
  }
  if (failures === beforeCase4) pass('every RELIABLE_RULES entry is configured by its package');

  // ── Case 1 + Case 2: for every rule this repo can actually measure
  // (pinned by a fixture in expected.json, i.e. proven reachable through
  // review.js), the package's own declared severity must equal what
  // review.js effectively reports. A mismatch here is either:
  //   - case 1, in spirit: the rule fires but at the wrong severity, which
  //     is observationally identical to "missing from the effective set" at
  //     the level that matters (whether it blocks the PR) whenever declared
  //     says blocker and effective says recommend or absent;
  //   - case 2: severity differs outright.
  //
  // Iterated per PACKAGE, not over one merged `{ruleId: severity}` map. A
  // merged map is keyed by bare rule id, so two packages declaring the same
  // id collapse into whichever was spread last — and
  // `shoptet/no-testid-selector` is declared by both the ESLint config
  // ('error') and the stylelint config (`true`). That id is in the ESLint
  // package's RELIABLE_RULES but deliberately NOT in the stylelint one, so
  // only the ESLint declaration can ever govern output; a merged map would
  // compare the stylelint declaration instead and report a divergence
  // against the wrong package the moment the two severities differ.
  //
  // Restricting the comparison to `reliable` pairs loses no detection:
  // Case 3 already flags a rule that is configured but absent from
  // RELIABLE_RULES, and Case 4 the reverse orphan.
  const beforeCase12 = failures;
  for (const { name, reliable, declared, runner } of packages) {
    for (const ruleId of reliable) {
      if (DELIBERATE_EXCLUSIONS.has(`${name}:${ruleId}`)) continue;
      const effectiveSeverity = effective[ruleId];
      // Not pinned by any fixture — the completeness check below catches it
      // from the other direction.
      if (effectiveSeverity === undefined) continue;
      const declaredSeverity = runner.has(ruleId) ? RUNNER_SEVERITY[ruleId] : declared[ruleId];
      // Not declared by this package's own config — Case 4's territory.
      if (declaredSeverity === undefined) continue;
      if (declaredSeverity !== effectiveSeverity) {
        fail(
          `[${name}] ${ruleId}: declared ${declaredSeverity} in its package's config but ` +
            `review.js effectively reports it as ${effectiveSeverity} (test-cases/expected.json)`,
        );
      }
    }
  }
  if (failures === beforeCase12) {
    pass('every fixture-measured rule’s effective severity matches its declared severity');
  }

  // ── Completeness in the other direction: every RELIABLE_RULES rule (across
  // all three packages, i.e. what profiles.js reports) must be measurable —
  // present in expected.json — so this equality test can never be silently
  // blind to a rule nobody's fixture pins. (test/selftest.js's own section 5
  // enforces the same thing for fixture-coverage reasons; restated here so
  // this file is independently meaningful.)
  const beforeCoverage = failures;
  const COVERAGE_EXEMPT = new Set(['stylelint/parse-error']);
  const mergedReliable = new Set([
    ...eslintPkg.RELIABLE_RULES,
    ...stylelintPkg.RELIABLE_RULES,
    ...htmlPkg.RELIABLE_RULES,
  ]);
  for (const ruleId of mergedReliable) {
    if (COVERAGE_EXEMPT.has(ruleId)) continue;
    if (!(ruleId in effective)) {
      fail(`${ruleId}: in the merged RELIABLE_RULES set but not measurable via expected.json`);
    }
  }
  if (failures === beforeCoverage) pass('every RELIABLE_RULES entry is measurable');

  if (failures > 0) {
    console.error(`\n${failures} rule-equality failure(s).`);
    process.exitCode = 1;
  } else {
    console.log('\nRule set equality holds: declared == effective, by id and severity.');
  }
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
